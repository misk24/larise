begin;

create extension if not exists pgtap with schema extensions;

select plan(33);

select ok(
  (select relrowsecurity from pg_class where oid = 'public.profiles'::regclass),
  'profiles has RLS enabled'
);
select ok((select relrowsecurity from pg_class where oid = 'public.themes'::regclass), 'themes has RLS enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.theme_sections'::regclass), 'theme_sections has RLS enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.invitations'::regclass), 'invitations has RLS enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.invitation_sections'::regclass), 'invitation_sections has RLS enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.invitation_media'::regclass), 'invitation_media has RLS enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.guests'::regclass), 'guests has RLS enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.rsvps'::regclass), 'rsvps has RLS enabled');
select ok((select relrowsecurity from pg_class where oid = 'public.wishes'::regclass), 'wishes has RLS enabled');

select ok(
  exists(select 1 from pg_constraint where conrelid = 'public.invitations'::regclass and conname = 'invitations_slug_key'),
  'invitation slug is unique'
);
select ok(
  exists(select 1 from pg_constraint where conrelid = 'public.invitations'::regclass and conname = 'invitations_status_check'),
  'invitation status is constrained'
);
select ok(
  exists(select 1 from pg_constraint where conrelid = 'public.rsvps'::regclass and conname = 'rsvps_status_check'),
  'RSVP status is constrained'
);
select ok(
  exists(select 1 from pg_constraint where conrelid = 'public.wishes'::regclass and conname = 'wishes_visibility_check'),
  'wish visibility is constrained'
);
select ok(
  exists(select 1 from pg_policies where schemaname='public' and tablename='invitations' and policyname='Users read own invitations'),
  'invitation owner read policy exists'
);
select ok(
  exists(select 1 from pg_policies where schemaname='public' and tablename='invitations' and policyname='Users update own invitations'),
  'invitation owner update policy exists'
);
select ok(
  exists(select 1 from pg_policies where schemaname='public' and tablename='invitations' and policyname='Users delete own invitations'),
  'invitation owner delete policy exists'
);
select ok(
  exists(select 1 from pg_policies where schemaname='public' and tablename='invitations' and policyname='Public read published invitations'),
  'published invitation public read policy exists'
);
select ok(
  exists(select 1 from pg_policies where schemaname='public' and tablename='guests' and policyname='Users manage own guests'),
  'guest ownership policy exists'
);
select ok(
  exists(select 1 from pg_policies where schemaname='public' and tablename='rsvps' and policyname='Users manage own rsvps'),
  'RSVP ownership policy exists'
);

select ok(
  exists(select 1 from pg_policies where schemaname='public' and tablename='invitation_sections' and policyname='Owners manage sections for own invitations'),
  'invitation section owner policy exists'
);
select ok(
  exists(select 1 from pg_policies where schemaname='public' and tablename='invitation_media' and policyname='Owners manage media for own invitations'),
  'invitation media owner policy exists'
);

select ok(
  exists(
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname = 'save_invitation_sections_atomic'
      and p.prosecdef = false
  ),
  'atomic builder save function exists and runs with caller privileges'
);

select ok(
  exists (
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname = 'update_invitation_settings_atomic'
      and p.prosecdef = false
      and has_function_privilege('authenticated', p.oid, 'EXECUTE')
  ),
  'atomic invitation settings function exists, is invoker-security, and is executable by authenticated users'
);


select ok(
  exists(
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'guests'
      and column_name = 'public_token'
      and is_nullable = 'NO'
      and column_default is not null
  ),
  'guest public token is required and generated by default'
);

select ok(
  (select count(*) = 3
   from pg_proc p
   join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public'
     and p.proname in ('submit_guest_rsvp', 'resolve_public_guest', 'submit_guest_wish')
     and p.prosecdef = true),
  'public guest RPCs use definer security'
);

select ok(
  (select count(*) = 3
   from pg_proc p
   join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public'
     and p.proname in ('submit_guest_rsvp', 'resolve_public_guest', 'submit_guest_wish')
     and has_function_privilege('anon', p.oid, 'EXECUTE')
     and has_function_privilege('authenticated', p.oid, 'EXECUTE')),
  'public guest RPCs are executable by anon and authenticated roles'
);

select ok(
  (select pg_get_functiondef(p.oid) like '%Batas ucapan untuk tamu ini%' and pg_get_functiondef(p.oid) like '%for update of g%'
   from pg_proc p
   join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'submit_guest_wish'),
  'submit_guest_wish limits wishes per guest and serializes concurrent submissions'
);

select ok(
  not exists(select 1 from pg_policies where schemaname='public' and tablename='guests' and cmd='INSERT' and roles && array['anon']::name[]),
  'anonymous clients cannot directly insert guests'
);

select ok(
  not exists(select 1 from pg_policies where schemaname='public' and tablename='rsvps' and cmd in ('INSERT', 'UPDATE') and roles && array['anon']::name[]),
  'anonymous clients cannot directly insert or update RSVPs'
);

select ok(
  not exists(select 1 from pg_policies where schemaname='public' and tablename='wishes' and cmd='INSERT' and roles && array['anon']::name[]),
  'anonymous clients cannot directly insert wishes'
);

select ok(
  not has_table_privilege('anon', 'public.rsvps', 'INSERT')
  and not has_table_privilege('anon', 'public.rsvps', 'UPDATE')
  and not has_table_privilege('anon', 'public.rsvps', 'DELETE'),
  'anonymous role has no direct RSVP mutation privileges'
);

select ok(
  not has_table_privilege('anon', 'public.wishes', 'INSERT'),
  'anonymous role has no direct wish insert privilege'
);

select ok(
  exists(
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname = 'submit_guest_rsvp'
      and has_function_privilege('anon', p.oid, 'EXECUTE')
  ),
  'guest RSVP submission is available through the verified RPC'
);

select * from finish();

rollback;
